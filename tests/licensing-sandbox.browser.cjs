const assert=require('node:assert/strict');
const http=require('node:http');
const fs=require('node:fs/promises');
const path=require('node:path');
const {chromium}=require('../checks.local/node_modules/playwright-core');
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const mime={'.html':'text/html','.js':'application/javascript','.css':'text/css','.wasm':'application/wasm','.data':'application/octet-stream','.svg':'image/svg+xml'};
(async()=>{
  const {app:{security:{csp}}}=JSON.parse(await fs.readFile('licensing-sandbox/src-tauri/tauri.conf.json','utf8'));
  const server=http.createServer(async(req,res)=>{
    const pathname=new URL(req.url,'http://localhost').pathname;
    res.setHeader('Content-Security-Policy',csp);
    try {res.setHeader('Content-Type',mime[path.extname(pathname)]??'text/html');res.end(await fs.readFile(path.join('licensing-sandbox/dist.local',pathname.includes('.')?pathname:'/index.html')));}
    catch{res.writeHead(404).end();}
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  try{
    const context=await browser.newContext({viewport:{width:1400,height:1000}});
    const page=await context.newPage();page.setDefaultTimeout(15000);page.on('dialog',dialog=>dialog.accept());
    const errors=[],external=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
    const origin='http://127.0.0.1:'+server.address().port;
    page.on('request',request=>{if(/^https?:/.test(request.url())&&!request.url().startsWith(origin+'/'))external.push(request.url());});
    await page.goto(origin);
    await page.getByRole('form',{name:'Novo monitoramento fictício'}).waitFor({timeout:30000}).catch(async error=>{console.log(await page.locator('body').innerText(),errors);throw error;});
    const selectUser=async(n)=>{
      await page.getByLabel('Simular usuário',{exact:true}).selectOption(id(n));
      await page.waitForFunction(()=>!document.body.textContent.includes('Iniciando o banco de demonstração'));
    };
    const farmSelect=page.getByLabel('Fazenda autorizada',{exact:true});
    assert.deepEqual(await farmSelect.locator('option').allTextContents(),['Fazenda Aurora · fictícia']);
    await selectUser(5);
    assert.equal(await page.getByRole('button',{name:'Estoque e aplicações',exact:true}).count(),0);
    assert.equal(await page.getByText('Relatório demonstrativo da proprietária.',{exact:true}).count(),0);
    const report=page.getByRole('form',{name:'Novo monitoramento fictício'});
    await report.getByLabel('Estádio fenológico',{exact:true}).fill('V5');
    await report.getByLabel('Relatório',{exact:true}).fill('Relatório fictício da Eva');
    await report.getByRole('button',{name:'Salvar monitoramento'}).click();
    const eva=page.getByRole('article',{name:'Monitoramento: Relatório fictício da Eva'});
    await eva.waitFor();
    await eva.getByRole('button',{name:'Editar',exact:true}).click();
    const edit=page.getByRole('form',{name:'Editar registro fictício'});
    await edit.getByLabel('Estádio fenológico',{exact:true}).fill('V6');
    await edit.getByRole('button',{name:'Salvar alteração'}).click();
    await eva.getByText('Talhão Sol · V6',{exact:true}).waitFor();
    const rain=page.getByRole('form',{name:'Nova chuva fictícia'});
    await rain.getByLabel('Chuva (mm)',{exact:true}).fill('25');
    await rain.getByRole('button',{name:'Salvar chuva'}).click();
    await page.getByText('Talhão Sol · 25 mm',{exact:true}).waitFor();
    await selectUser(1);
    await page.getByRole('button',{name:'Equipe e convites',exact:true}).click();
    await page.getByLabel('Conta convidada',{exact:true}).selectOption('fabio@example.test');
    await page.getByRole('button',{name:'Criar convite',exact:true}).click();
    await page.getByText('Convite fictício criado. Simule a conta destinatária para aceitar.',{exact:true}).waitFor();
    await selectUser(7);
    await page.getByRole('heading',{name:'Nenhuma fazenda autorizada',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Aceitar convite',exact:true}).count(),0);
    await selectUser(6);
    await page.getByRole('button',{name:'Aceitar convite',exact:true}).click();
    await page.getByText('Convite aceito. Selecione a fazenda autorizada.',{exact:true}).waitFor();
    await farmSelect.selectOption(id(101));
    await page.getByRole('button',{name:'Estoque e aplicações',exact:true}).click();
    await page.getByText('100 unidades',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Registrar aplicação fictícia',exact:true}).count(),0);
    await page.getByRole('button',{name:'Monitoramento e chuvas',exact:true}).click();
    assert.equal(await eva.getByRole('button',{name:'Editar',exact:true}).count(),0);
    const recommendation=page.getByRole('form',{name:'Nova recomendação fictícia'});
    await recommendation.getByLabel('Orientações',{exact:true}).fill('Recomendação fictícia sem baixa de estoque');
    await recommendation.getByRole('button',{name:'Salvar recomendação',exact:true}).click();
    await page.getByText('Recomendação fictícia sem baixa de estoque',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Estoque e aplicações',exact:true}).click();
    await page.getByText('100 unidades',{exact:true}).waitFor();
    assert.equal((await farmSelect.locator('option').allTextContents()).some(name=>name.includes('Boa Vista')),false);
    await selectUser(1);
    await page.getByRole('button',{name:'Equipe e convites',exact:true}).click();
    const fabio=page.getByRole('article').filter({has:page.getByText('Fábio',{exact:true})}).filter({has:page.getByRole('button',{name:'Revogar acesso',exact:true})});
    await fabio.getByRole('button',{name:'Revogar acesso',exact:true}).click();
    await page.getByText('Vínculo revogado. Os registros foram preservados.',{exact:true}).waitFor();
    await selectUser(6);
    assert.deepEqual(await farmSelect.locator('option').allTextContents(),['Fazenda Cedro · fictícia']);
    await page.reload();
    await page.getByRole('form',{name:'Novo monitoramento fictício'}).waitFor({timeout:30000});
    await page.getByText('Relatório fictício da Eva',{exact:true}).waitFor();
    await page.screenshot({path:'checks.local/license-lab-preview.png',fullPage:true});
    assert.deepEqual(external,[],'The prototype must never contact production or external services');
    assert.deepEqual(errors,[]);
    console.log('PASS: local PostgreSQL under native CSP, monitor CRUD, targeted invitation, consultant read-only stock, recommendation without debit, revocation, persistence and zero external requests');
  }finally{await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
