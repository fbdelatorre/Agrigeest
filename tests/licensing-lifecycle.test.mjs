 const employee=(await call(null,'register_demo',['Joana','joana@example.test',true,token]))[0].value;
 await as(employee,"INSERT INTO license_lab.reports(farm_id,area_id,author_id,observed_on,stage,description) VALUES($1,$2,$3,CURRENT_DATE,'V6','Preservar Joana')",[id(101),id(201),employee]);
