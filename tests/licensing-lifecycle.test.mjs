 const devices=(await as(1,'SELECT id FROM license_lab.devices WHERE active')).slice(0,2).map(d=>d.id);
 const key=randomUUID();await call(1,'dismiss',[id(101),employee,true,devices,key]);await call(1,'dismiss',[id(101),employee,true,devices,key]);
 assert.equal((await as(employee,'SELECT * FROM license_lab.farms')).length,0);
