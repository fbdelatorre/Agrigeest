 await call(1,'plan_change',[id(101),'buy_extra',[],randomUUID()]);
 const rehire=(await call(1,'invite',[id(101),'joana@example.test','operator']))[0].value;await call(employee,'accept_invitation',[rehire]);
 await call(1,'dismiss',[id(101),employee,false,[],randomUUID()]);
