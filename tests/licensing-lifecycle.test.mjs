 assert.equal((await as(1,"UPDATE license_lab.reports SET stage='V99' RETURNING id")).length,0);
 assert.equal((await as(1,'DELETE FROM license_lab.reports RETURNING id')).length,0);
 await assert.rejects(as(1,"INSERT INTO license_lab.rainfall(farm_id,area_id,author_id,observed_on,millimeters) VALUES($1,$2,$3,CURRENT_DATE,25)",[id(101),id(201),id(1)]),/READ_ONLY_LICENSE|row-level security/);
